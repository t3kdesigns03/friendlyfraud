// Embeds supabase/migrations/*.sql into src/lib/db/migrations.generated.ts so
// the app can migrate its database on serverless hosts (where the SQL files
// aren't on disk at runtime). Runs automatically before dev and build.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((name) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(path.join(dir, name), "utf8"))} },`).join("\n");
writeFileSync(
  "src/lib/db/migrations.generated.ts",
  `// GENERATED by scripts/gen-migrations.mjs from supabase/migrations — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`,
);
console.log(`embedded ${files.length} migration(s)`);
